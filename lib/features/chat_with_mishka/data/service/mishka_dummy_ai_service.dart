  /// Simulate chat endpoint
  /// POST /chat(session_id, message) -> { response }
  Future<String> chat({
    required String sessionId,
    required String message,
  }) async {
    // Simulate network delay
    await Future.delayed(const Duration(milliseconds: 800));

    // Simple deterministic response based on message
    if (message.toLowerCase().contains('hello')) {
      return 'Hello! I\'m Mishka, your study partner. How can I help you today?';
    }
    if (message.toLowerCase().contains('how') || message.toLowerCase().contains('what')) {
      return 'I can help you with quizzes, flashcards, and mind maps based on this content!';
    }
    if (message.toLowerCase().contains('explain')) {
      return 'This is a comprehensive study guide. Feel free to ask me anything specific about the material.';
    }
    if (message.toLowerCase().contains('thank')) {
      return 'You\'re welcome! Keep up the great work! 📚';
    }
    return 'Great question! That\'s an important concept. Would you like me to explain it further?';
  }

