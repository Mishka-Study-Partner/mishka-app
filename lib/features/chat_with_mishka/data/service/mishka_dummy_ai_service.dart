  String _buildExplanation(String summaryLevel) {
    if (summaryLevel.toLowerCase() == 'simple') {
      return """
📘 Embedded Systems – Interrupts (Simple Explanation)

An interrupt is an event that forces the CPU to stop its normal program
execution and handle an urgent task.

🔹 Types of Interrupts:
• Internal interrupts: generated inside the microcontroller
  (e.g. timer overflow)
• External interrupts: generated by external signals
  (e.g. I/O pin state change)

🔹 PIC18F452 Interrupt Sources:
• External interrupts (INT0, INT1, INT2)
• PORTB change interrupts (RB4–RB7)
• Timer interrupts (Timer 0–3)
• Serial communication interrupts
• ADC and CCP interrupts

🔹 Interrupt Control:
Each interrupt has:
• Enable bit (IE) → turns interrupt on/off
• Flag bit (IF) → indicates interrupt occurred
• Priority bit (IP) → high or low priority

🔹 Important Notes:
• Flag bits must be cleared in software
• INT0 is always high priority
• High-priority interrupts can interrupt low-priority ones

This lecture explains how interrupts are configured, prioritized,
and handled in PIC microcontrollers.
""";
    } else {
      return """
📘 Embedded Systems – Interrupts (Detailed Explanation)

An interrupt is a mechanism that allows the CPU to temporarily suspend
normal execution to respond to time-critical events.

🔹 Interrupt Sources in PIC18F452:
• External interrupts on RB0/INT0, RB1/INT1, RB2/INT2
• PORTB change interrupts (RB4–RB7)
• Timer overflow interrupts (TMR0–TMR3)
• Serial communication interrupts (TX, RX)
• ADC conversion complete
• CCP modules

🔹 Interrupt Control Bits:
Each interrupt source is controlled by:
1) IE (Interrupt Enable)
2) IF (Interrupt Flag)
3) IP (Interrupt Priority)

An interrupt is recognized only if:
• Enable bit = 1
• Flag bit = 1
• Global interrupt enable is active

🔹 Priority System:
• High-priority interrupts vector to address 0x0008
• Low-priority interrupts vector to address 0x0018
• High-priority interrupts can interrupt low-priority routines
• Priority can be disabled, making all interrupts equal

🔹 Registers Used:
• RCON → enables priority structure
• INTCON, INTCON2, INTCON3
• PIR1, PIR2 → interrupt flags
• PIE1, PIE2 → interrupt enables
• IPR1, IPR2 → interrupt priorities

🔹 External Interrupt Behavior:
• Edge-triggered (rising or falling)
• INT0 has fixed high priority
• INT1 and INT2 are configurable

🔹 PORTB Change Interrupt:
• Triggered by any change on RB4–RB7
• One enable bit and one flag for all pins

🔹 Practical Examples:
The lecture demonstrates configuring INT1 for:
• Falling-edge, low priority
• Rising-edge, high priority

This provides a complete foundation for interrupt handling
in embedded systems.
""";
    }
